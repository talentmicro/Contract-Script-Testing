function runGenerateScript(generateScript, v_headerDetails, form_details) {
  let decimal;
  try {
    //   decimal = offer_generation_obj['list'][0]['decimalSupport'] || 0;
    decimal = 0;
  } catch (err) {
    decimal = 0;
  }
  let scriptList;
  if (generateScript) {
    try {
      scriptList = JSON.parse(generateScript);
    } catch (err) {
      console.error("Invalid generateScript JSON:", err);
      return v_headerDetails;
    }

    for (const s of scriptList) {
      if (!s.condition) continue;

      try {
        (function (v_headerDetails, form_details) {
          v_headerDetails = eval(s.condition);
        })(v_headerDetails, form_details);
      } catch (err) {
        console.error("Error executing condition:", s.condition, err);
      }
    }
  } else {
    try {
      for (const header of v_headerDetails) {
        if (header && header.script) {
          try {
            header["amount"] = eval(header.script);
          } catch (error) {
            header["amount"] = header["value"];
          }
        } else {
          header["amount"] = header["value"];
        }
        //Header formating based on decimal
        try {
          if (isNaN(header["amount"])) {
          } else {
            header["amount"] = parseFloat(header["amount"]).toFixed(decimal);
          }
        } catch (err) {}

        //column 2 calculation
        try {
          if (
            (header["column2Multiplier"] || header["column2Multiplier"] == 0) &&
            !isNaN(header["amount"])
          ) {
            header["column2"] = header["amount"] * header["column2Multiplier"];
          }
        } catch (error) {}

        try {
          if (isNaN(header["column2"])) {
          } else {
            header["column2"] = parseFloat(header["column2"]).toFixed(decimal);
          }
        } catch (err) {}
      }
    } catch (err) {
      console.error("Formatting/column2 calculation error:", err);
    }
  }

  return v_headerDetails;
}

function transformHeaders(v_headerDetails) {
  return v_headerDetails.map((header, index) => {
    return {
      id: 0,
      amount: header.amount ?? null,
      column2: header.column2 ?? null,
      formula: "Fixed",
      dataType: header.dataType,
      editable: header.editable,
      headerCode: header.headerCode,
      masterData: header.masterData || [],
      displayName: header.displayName,
      masterValue: header.masterValue || null,
      column1Title: "annually",
      column2Title: "monthly",
      visibilityFlag: header.visibilityFlag,
      column2Multiplier: header.column2Multiplier,
    };
  });
}

